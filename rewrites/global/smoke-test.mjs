import assert from 'node:assert/strict';
import { FEEDS, SHARD_COUNT, MAJOR_FEEDS, currentWindow, scheduledStage, extractJsonArray, canonicalLink, eventKey, isPotentialMajor } from './index.js';
assert.equal(FEEDS.length, 35, `expected 35 daily feeds, got ${FEEDS.length}`);
assert.equal(SHARD_COUNT, 35, `expected one feed per shard, got ${SHARD_COUNT}`);
assert.equal(MAJOR_FEEDS.length, 6);
const utc = (h,m) => Date.UTC(2026, 9, 27, h, m) - 8*60*60*1000;
assert.equal(scheduledStage(utc(5,40)), 'fetch');
assert.equal(scheduledStage(utc(5,50)), 'digest');
assert.equal(scheduledStage(utc(6,0)), 'send');
assert.equal(scheduledStage(utc(21,40)), 'fetch');
assert.equal(scheduledStage(utc(21,50)), 'digest');
assert.equal(scheduledStage(utc(22,0)), 'send');
for (const [h,m] of [[0,0],[1,40],[5,0],[6,40],[12,0],[21,0],[22,40],[23,50]]) assert.equal(scheduledStage(utc(h,m)), null, `unexpected stage at ${h}:${m}`);
assert.match(currentWindow(utc(6,0)), /-am$/);
assert.match(currentWindow(utc(22,0)), /-pm$/);
assert.equal(canonicalLink('https://Example.com/a/?utm_source=x#frag'), 'https://example.com/a');
assert.equal(eventKey({link:'https://example.com/x?ref=abc'}), 'https://example.com/x');
assert.deepEqual(extractJsonArray('text ```json\n[{"idx":1}]\n``` tail'), [{idx:1}]);
const major = {srcId:'openai', title:'OpenAI launches GPT-9 frontier model', desc:'A new reasoning model is available', link:'https://openai.com/news/gpt-9', ts:Date.now(), source:'OpenAI'};
assert.equal(isPotentialMajor(major), true);
const routine = {srcId:'openai', title:'OpenAI blog: small product update', desc:'New feature for an existing app', link:'https://openai.com/news/small-update', ts:Date.now(), source:'OpenAI'};
assert.equal(isPotentialMajor(routine), false);
console.log('GUJI smoke tests passed');
